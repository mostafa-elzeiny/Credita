// Helper to encode string to UTF-16LE Uint8Array (Power BI standard UTF-16LE without BOM)
function encodeUtf16Le(str: string, includeBom = false): Uint8Array {
  const bomOffset = includeBom ? 2 : 0;
  const buf = new Uint8Array(bomOffset + str.length * 2);
  if (includeBom) {
    buf[0] = 0xff;
    buf[1] = 0xfe;
  }
  for (let i = 0; i < str.length; i++) {
    const code = str.charCodeAt(i);
    buf[bomOffset + i * 2] = code & 0xff;
    buf[bomOffset + i * 2 + 1] = (code >> 8) & 0xff;
  }
  return buf;
}

