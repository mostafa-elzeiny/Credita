export async function buildCompletePowerBiSolution(dataList: FinancialData[]): Promise<PowerBiGenerationResult> {
  const summary = computeFinancialModel(dataList);
  
  // Clean, professional filename that supports Latin and Arabic characters without resulting in empty underscores
  const rawName = (summary.companyName || '').trim();
  let cleanName = rawName
    .replace(/[\\/:*?"<>|]/g, '')
    .replace(/\s+/g, '_')
    .slice(0, 40);
  if (!cleanName || /^_+$/.test(cleanName)) {
    cleanName = 'Financial_Analysis';
  }
  
  // Generate Excel workbook buffer and base64
  const { blob: xlsxBlob, base64: xlsxBase64 } = generatePowerBiExcelWorkbookBuffer(summary, dataList);

  // 1. Standalone Interactive Report (.html) - Opens instantly in any browser without needing Power BI installed!
  const htmlReportText = generateStandaloneHtmlReport(summary, xlsxBase64);
  const htmlFileName = `${cleanName}_Interactive_Dashboard.html`;
  const htmlBlob = new Blob([htmlReportText], { type: 'text/html;charset=utf-8' });

  // 2. Power BI Template and PBIX
  const pbitBlob = await (generatePowerBiTemplateFile(summary) as unknown as Promise<Blob>);
  const daxText = generateDaxMeasuresScript(summary);
  const guideText = generatePowerBiQuickStartGuide(summary);
  const mScriptText = generatePowerQueryMScript(summary);
  const dataModelSchema = buildPowerBiDataModelSchema(summary);
  const reportLayout = buildPowerBiReportLayout(summary);

  // Build the complete Master ZIP kit
  const masterZip = new JSZip();
  const pbixFileName = `${cleanName}_Financial_Dashboard.pbix`;
  const pbitFileName = `${cleanName}_Ready_Dashboard.pbit`;
  const xlsxFileName = `${cleanName}_Financial_Model.xlsx`;
  const daxFileName = `${cleanName}_DAX_Measures.dax`;
  const mScriptFileName = 'PowerQuery_Import_Script.m';
  const guideFileName = 'PowerBI_QuickStart_Guide.txt';
  const zipFileName = `${cleanName}_PowerBI_Complete_Kit.zip`;

  // pbixBlob with specific mime type
  const pbixBlob = new Blob([pbitBlob], { type: 'application/vnd.ms-powerbi.desktop' });

  masterZip.file(htmlFileName, htmlBlob);
  masterZip.file(pbixFileName, pbixBlob);
  masterZip.file(pbitFileName, pbitBlob);
  masterZip.file(xlsxFileName, xlsxBlob);
  masterZip.file(daxFileName, daxText);
  masterZip.file(mScriptFileName, mScriptText);
  masterZip.file(guideFileName, guideText);

  // Modern Power BI Project (.pbip) files inside the kit - Opens natively with ALL visual pages & measures
  const pbipProjectName = `${cleanName}_Project`;
  masterZip.file(`${pbipProjectName}.pbip`, JSON.stringify({
    version: "1.0",
    artifacts: [
      {
        report: {
          path: `${pbipProjectName}.Report`
        }
      }
    ],
    settings: {
      enableAutoAuth: true
    }
  }, null, 2));

  masterZip.file(`${pbipProjectName}.Report/definition.pbir`, JSON.stringify({
    version: "1.0",
    datasetReference: {
      byPath: {
        path: `../${pbipProjectName}.SemanticModel`
      },
      byConnection: null
    }
  }, null, 2));

  // The actual Report visual layout containing all 5 prebuilt dashboard pages & visuals
  masterZip.file(`${pbipProjectName}.Report/report.json`, JSON.stringify(reportLayout, null, 2));

  masterZip.file(`${pbipProjectName}.SemanticModel/definition.pbism`, JSON.stringify({
    version: "1.0"
  }, null, 2));

  // The Tabular Model containing all tables, columns, and DAX measures
  masterZip.file(`${pbipProjectName}.SemanticModel/model.bim`, JSON.stringify(dataModelSchema, null, 2));

  const zipBlob = await masterZip.generateAsync({
    type: 'blob',
    mimeType: 'application/zip',
    compression: 'DEFLATE'
  });

  return {
    htmlBlob,
    htmlFileName,
    htmlText: htmlReportText,
    pbixBlob,
    pbixFileName,
    pbitBlob,
    pbitFileName,
    xlsxBlob,
    xlsxFileName,
    xlsxBase64,
    daxText,
    daxFileName,
    guideText,
    mScriptText,
    mScriptFileName,
    zipBlob,
    zipFileName
  };
}
